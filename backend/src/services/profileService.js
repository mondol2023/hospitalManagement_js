'use strict';

const crypto = require('crypto');

const {
  patientRepository,
  doctorRepository,
  nurseRepository,
  staffRepository,
} = require('../repositories');
const ApiError = require('../utils/ApiError');
const { ROLES, ROLE_PROFILE_MODEL, STAFF_ROLES } = require('../utils/constants');

/**
 * Resolves the *profile* that backs a user account.
 *
 * Every account is a `User` row plus exactly one profile document — Patient,
 * Doctor, Nurse or Staff. The original code scattered that mapping across the
 * controllers, so a `pharmacist` could be created with no profile at all and a
 * doctor could end up with two. One module owns the mapping now, and everything
 * that needs "the profile for this user" goes through it.
 *
 * The employee-number prefix and the per-role required fields live here for the
 * same reason: adding a role means editing this file and `constants.js`, nothing
 * else.
 */

const REPOSITORIES = Object.freeze({
  Patient: patientRepository,
  Doctor: doctorRepository,
  Nurse: nurseRepository,
  Staff: staffRepository,
});

const EMPLOYEE_ID_PREFIX = Object.freeze({
  [ROLES.DOCTOR]: 'DOC',
  [ROLES.NURSE]: 'NUR',
  [ROLES.RECEPTIONIST]: 'REC',
  [ROLES.PHARMACIST]: 'PHA',
  [ROLES.ACCOUNTANT]: 'ACC',
  [ROLES.MANAGER]: 'MGR',
  [ROLES.ADMIN]: 'ADM',
});

class ProfileService {
  /**
   * @param {string} role
   * @returns {import('../repositories/BaseRepository')} the repository holding
   *   this role's profiles
   */
  repositoryFor(role) {
    const modelName = ROLE_PROFILE_MODEL[role];
    const repository = modelName && REPOSITORIES[modelName];
    if (!repository) throw ApiError.badRequest(`No profile is defined for role "${role}"`);
    return repository;
  }

  /**
   * @param {string} role
   * @returns {string} name of the model holding this role's profile — two roles
   *   with the same value share one collection (and one row per user)
   */
  modelFor(role) {
    return ROLE_PROFILE_MODEL[role];
  }

  /**
   * Employee numbers must be unique and are usually issued by HR. When a caller
   * omits one we mint a collision-resistant value rather than rejecting the
   * request — a random suffix, not a counter, because a counter document would
   * serialise every hire through one hot key.
   */
  generateEmployeeId(role) {
    const prefix = EMPLOYEE_ID_PREFIX[role] || 'EMP';
    return `${prefix}-${crypto.randomBytes(4).toString('hex').toUpperCase()}`;
  }

  /**
   * Creates the profile that matches `role`.
   *
   * Takes the session so it commits with the `User` insert that precedes it —
   * a user with no profile is a broken account, and half of it must not survive
   * a failure.
   *
   * @param {object} args
   * @param {string} args.userId
   * @param {string} args.role
   * @param {object} [args.profile] role-specific fields from the request
   * @param {object} [options]
   */
  createProfile({ userId, role, profile = {} }, { session } = {}) {
    const repository = this.repositoryFor(role);
    const payload = { ...profile, user: userId };

    if (role === ROLES.PATIENT) {
      // MRN is generated by the model's pre-validate hook; clients cannot set it.
      delete payload.medicalRecordNumber;
    } else {
      payload.employeeId = payload.employeeId
        ? String(payload.employeeId).toUpperCase().trim()
        : this.generateEmployeeId(role);
    }

    // `Staff` stores the account role alongside `User.role` so the directory can
    // filter without a join; keep the two in lockstep at the single write site.
    if (ROLE_PROFILE_MODEL[role] === 'Staff') payload.role = role;

    return repository.create(payload, { session });
  }

  /** @returns {Promise<object|null>} lean profile, or null when none exists yet. */
  findByUser(userId, role) {
    return this.repositoryFor(role).findByUser(userId);
  }

  /**
   * Same as `findByUser` but 404s instead of returning null — for the endpoints
   * where a missing profile means the request cannot proceed.
   */
  async requireByUser(userId, role) {
    const profile = await this.findByUser(userId, role);
    if (!profile) throw ApiError.notFound(`${ROLE_PROFILE_MODEL[role]} profile`);
    return profile;
  }

  /**
   * Merges a user with its profile for `GET /me`-style responses, so the client
   * gets one object instead of having to stitch two calls together.
   */
  async withProfile(user) {
    if (!user) return null;
    const profile = await this.findByUser(user._id || user.id, user.role).catch(() => null);
    return { ...user, profile: profile || null };
  }

  /** True for every role that is an employee rather than a patient. */
  isStaffRole(role) {
    return STAFF_ROLES.includes(role);
  }

  /** Removes the profile — used when rolling back a failed account creation. */
  deleteForUser(userId, role, { session } = {}) {
    return this.repositoryFor(role).deleteMany({ user: userId }, { session });
  }
}

module.exports = new ProfileService();
module.exports.ProfileService = ProfileService;
